import { testDatabaseUrl } from './database.js';
import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import request from 'supertest';
import bcrypt from 'bcrypt';
import jwt from 'jsonwebtoken';
import { createApp } from '../app.js';
import { createPrisma } from '../lib/prisma.js';

const db = new pg.Pool({ connectionString: testDatabaseUrl() });
const prisma = createPrisma(testDatabaseUrl());
const app = createApp(db, { prisma });
const emails = [];
after(async () => { await prisma.user.deleteMany({ where: { email: { in: emails } } }); for (const store of app.locals.sessionStores) { await store.shutdown?.(); store.close?.(); } await prisma.$disconnect(); await db.end(); });
test('blog JWT protects drafts, publishes posts and moderates comments', async () => {
  const email = 'author-' + Date.now() + '@example.test'; emails.push(email);
  const password = 'Learning-Blog-123';
  const author = await prisma.user.create({ data: { email, passwordHash: await bcrypt.hash(password, 12), firstName: 'Blog', lastName: 'Writer', admin: true } });
  const login = await request(app).post('/blog/api/auth/login').send({ email, password }).expect(200);
  const token = login.body.token;
  assert.equal(jwt.decode(token).sub, String(author.id));
  assert.equal(login.body.user.passwordHash, undefined);
  const bearer = 'Bearer ' + token;
  const content = { title: 'Private draft', content: 'An unpublished article.', published: false };
  await request(app).post('/blog/api/posts').send(content).expect(401);
  const created = await request(app).post('/blog/api/posts').set('Authorization', bearer).send(content).expect(201);
  const id = created.body.post.id;
  await request(app).get('/blog/api/posts/' + id).expect(404);
  await request(app).get('/blog/api/posts?drafts=true').expect(401);
  await request(app).get('/blog/api/posts?drafts=true').set('Authorization', bearer).expect(200).expect(({ body }) => assert.ok(body.posts.some(p => p.id === id)));
  await request(app).post('/blog/api/posts/' + id + '/comments').send({ name: 'Reader', text: 'Hidden draft comment' }).expect(404);
  await request(app).put('/blog/api/posts/' + id).set('Authorization', bearer).send({ ...content, published: true }).expect(200);
  await request(app).get('/blog/api/posts/' + id).expect(200).expect(({ body }) => assert.equal(body.post.author.firstName, 'Blog'));
  const comment = await request(app).post('/blog/api/posts/' + id + '/comments').send({ name: 'Reader', text: 'Useful article' }).expect(201);
  const commentPath = '/blog/api/posts/' + id + '/comments/' + comment.body.comment.id;
  await request(app).put(commentPath).send({ name: 'Reader', text: 'Changed' }).expect(401);
  await request(app).put(commentPath).set('Authorization', bearer).send({ name: 'Reader', text: 'Edited comment' }).expect(200);
  await request(app).delete(commentPath).set('Authorization', bearer).expect(204);
  await request(app).get('/blog/api/posts?drafts=true').set('Authorization', 'Bearer invalid').expect(401);
  const expired = jwt.sign({}, process.env.JWT_SECRET, { subject: String(author.id), issuer: 'odin-blog', audience: 'odin-blog-author', expiresIn: -1 });
  await request(app).post('/blog/api/posts').set('Authorization', 'Bearer ' + expired).send(content).expect(401);
  await request(app).get('/blog/api/posts/not-a-number').expect(400);
  await prisma.user.update({ where: { id: author.id }, data: { admin: false } });
  await request(app).delete('/blog/api/posts/' + id).set('Authorization', bearer).expect(401);
  await prisma.user.update({ where: { id: author.id }, data: { admin: true } });
  await request(app).delete('/blog/api/posts/' + id).set('Authorization', bearer).expect(204);
});
